<?php

namespace Javaabu\Manifest\Commands;

use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Javaabu\Manifest\Manifest;

class TypesCommand extends Command
{
    protected $signature = 'manifest:types
                            {--path= : Where to write the page types (default resources/js/types/manifest.d.ts)}
                            {--no-tsconfig : Don\'t add the import paths to tsconfig.json}';

    protected $description = 'Add the packages\' import aliases to tsconfig.json and write types for their Inertia pages';

    public function handle(Manifest $manifest, Filesystem $files): int
    {
        $types_path = $this->option('path')
            ? base_path($this->option('path'))
            : resource_path('js/types/manifest.d.ts');

        $files->ensureDirectoryExists(dirname($types_path));
        $files->put($types_path, $this->pageTypes($manifest, dirname($types_path)));

        $this->components->info(__('manifest::messages.types.written', ['path' => $manifest->relativeToBase($types_path)]));

        if ($this->option('no-tsconfig')) {
            return self::SUCCESS;
        }

        return $this->updateTsconfig($manifest, $files);
    }

    protected function pageTypes(Manifest $manifest, string $directory): string
    {
        $lines = [
            '// Generated by `php artisan manifest:types`. Run it again after installing',
            '// or updating packages; don\'t edit this file.',
            'import type {} from "@javaabu/manifest/inertia"',
            '',
            'declare module "@javaabu/manifest/inertia" {',
            '  interface PackagePages {',
        ];

        foreach ($manifest->pages() as $name => $file) {
            $import = $this->relativePath($directory, $file);

            if (! str_ends_with($import, '.vue') && ! str_ends_with($import, '.svelte')) {
                $import = preg_replace('/\.[^.\/]+$/', '', $import);
            }

            $lines[] = '    ' . json_encode($name, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)
                . ': typeof import(' . json_encode($import, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ')';
        }

        return implode("\n", [...$lines, '  }', '}', '']);
    }

    protected function updateTsconfig(Manifest $manifest, Filesystem $files): int
    {
        $tsconfig_path = base_path('tsconfig.json');

        if (! $files->exists($tsconfig_path)) {
            $this->components->warn(__('manifest::messages.types.no_tsconfig'));
            $this->line($this->pathsSnippet($this->paths($manifest, base_path())));

            return self::SUCCESS;
        }

        $contents = $files->get($tsconfig_path);
        $tsconfig = json_decode($contents, true);

        if (! is_array($tsconfig)) {
            $this->components->warn(__('manifest::messages.types.cannot_update'));
            $this->line($this->pathsSnippet($this->paths($manifest, base_path())));

            return self::SUCCESS;
        }

        $base_url = $tsconfig['compilerOptions']['baseUrl'] ?? null;
        $paths_root = $base_url ? base_path(trim($base_url, '/')) : base_path();

        $tsconfig['compilerOptions'] ??= [];
        $tsconfig['compilerOptions']['paths'] = array_merge(
            $tsconfig['compilerOptions']['paths'] ?? [],
            $this->paths($manifest, $paths_root),
        );

        $json = json_encode($tsconfig, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);

        if (preg_match('/^\{\n( +)"/', $contents, $matches) && strlen($matches[1]) === 2) {
            $json = preg_replace_callback('/^( +)/m', fn (array $spaces) => str_repeat(' ', intdiv(strlen($spaces[1]), 2)), $json);
        }

        $files->put($tsconfig_path, $json . "\n");

        $this->components->info(__('manifest::messages.types.tsconfig_updated'));

        return self::SUCCESS;
    }

    /**
     * @return array<string, array<int, string>>
     */
    protected function paths(Manifest $manifest, string $root): array
    {
        $paths = [
            '@javaabu/manifest/inertia' => [$this->relativePath($root, realpath(__DIR__ . '/../../dist') . '/inertia.d.ts')],
        ];

        foreach ($manifest->packages() as $package) {
            $alias = $package->importAlias();

            if (! $alias) {
                continue;
            }

            $folder = $this->relativePath($root, $package->path($package->jsPath()));

            $paths[$alias] = [$folder];
            $paths["{$alias}/*"] = ["{$folder}/*"];
        }

        return $paths;
    }

    /**
     * @param  array<string, array<int, string>>  $paths
     */
    protected function pathsSnippet(array $paths): string
    {
        return json_encode(['compilerOptions' => ['paths' => $paths]], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    }

    /**
     * A path from a folder to a file, through vendor/ for symlinked packages.
     */
    protected function relativePath(string $from_directory, string $to): string
    {
        $manifest = app(Manifest::class);

        $to = $manifest->relativeToBase($to);

        // Outside the app (javaabu/manifest itself, in its own tests): absolute.
        if (str_starts_with($to, '/')) {
            return $to;
        }

        $from = explode('/', trim($manifest->relativeToBase($from_directory), '/'));
        $target = explode('/', trim($to, '/'));

        if ($from === ['']) {
            $from = [];
        }

        while ($from && $target && $from[0] === $target[0]) {
            array_shift($from);
            array_shift($target);
        }

        $relative = str_repeat('../', count($from)) . implode('/', $target);

        if (! str_starts_with($relative, '../')) {
            return "./{$relative}";
        }

        return $relative;
    }
}
